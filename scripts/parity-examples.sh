#!/usr/bin/env bash
# Run every program in examples/ on the portable core and report how far it
# gets, as a Markdown table (stdout).  Used by docs/parity.md and by the
# reg-rs test `parity-examples`, so any change in status — progress or
# regression — shows up as a diff to accept or fix.
#
#   scripts/parity-examples.sh                  (from the repository root)
#   scripts/parity-examples.sh --write          also rewrite docs/parity-examples.md
#
# Status values:
#   runs            exits normally, no error printed
#   missing: WORD   stopped at the first word the core does not define yet
#   fault: MESSAGE  a VM fault (bad address, unsupported instruction, ...)
#   error: MESSAGE  reva.f reported an error (a C function or library it
#                   could not load, ...)
#   timeout         still running after the time limit (interactive/looping)
# Area is a heuristic from the program's `needs` lines.
set -uo pipefail
cd "$(dirname "$0")/.."
REVA="${REVA:-target/debug/reva}"
LIMIT="${PARITY_TIMEOUT:-5}"
# Text filters use sed-rs (https://github.com/sw-cli-tools/sed-rs), not the
# system sed, so they behave the same on macOS, Linux and Windows.
SED_RS="${SED_RS:-$(command -v sed-rs || true)}"
[[ -n "$SED_RS" ]] || { echo "parity-examples: sed-rs not found; install it or set SED_RS" >&2; exit 2; }
root=.
abs_root=$(cd "$root" && pwd)
# Programs that `save` write an image to the working directory, so each
# runs in a scratch directory, not in the checkout.
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

area() {
    local n
    n=$(grep -hoE '^[[:space:]]*needs[[:space:]]+[^[:space:]]+' "$1" | awk '{print $2}' | tr '\n' ' ')
    case "$n" in
        *iup*|*gtk*|*ui/*|*gui*|*gl/*|*opengl*|*revagui*|*win*) echo "gui" ;;
        *net/*|*socket*) echo "net" ;;
        *db/*|*sqlite*|*mysql*) echo "db" ;;
        *os/*|*thread*|*process*|*shell*) echo "os" ;;
        "") echo "core" ;;
        *) echo "lib" ;;
    esac
}

classify() {
    local out code
    # tr: reva.f's REPL emits a NUL when it ends after an error
    out=$(cd "$work" && timeout "$LIMIT" "$abs_root/$REVA" "$abs_root/$1" < /dev/null 2>&1 | tr -d '\0'; exit "${PIPESTATUS[0]}")
    code=$?
    if [[ $code -eq 124 ]]; then echo "timeout"; return; fi
    local fault missing
    fault=$(grep -m1 -E '^\*\*\* ' <<<"$out" | "$SED_RS" -e 's/^\*\*\* //; s/ [(]in [^()]*, eip [^)]*[)]$//; s/[[:space:]]*$//')
    if [[ -n "$fault" ]]; then echo "fault: $fault"; return; fi
    # reva.f's handler: "ERROR: unknown word:  foo"; the bare core: "foo?"
    missing=$(grep -m1 -oE '^ERROR: unknown word: +[^[:space:]]+' <<<"$out" | awk '{print $NF}')
    [[ -n "$missing" ]] || missing=$(grep -m1 -E '^[^[:space:]]+\?$' <<<"$out" | "$SED_RS" -e 's/[?]$//')
    if [[ -n "$missing" ]]; then echo "missing: \`$missing\`"; return; fi
    local err
    err=$(grep -m1 -oE '^ERROR: .*' <<<"$out" | "$SED_RS" -e 's/^ERROR: //; s/[[:space:]]+/ /g; s/ *$//')
    if [[ -n "$err" ]]; then echo "error: $err"; return; fi
    echo "runs"
}

table=$(
    echo "| Example | Area | Status |"
    echo "|---|---|---|"
    (cd "$root" && find examples -type f \( -name '*.f' -o -name '*.4th' \) | LC_ALL=C sort) |
    while read -r f; do
        echo "| \`$f\` | $(area "$root/$f") | $(classify "$f") |"
    done
)
rows=$(echo "$table" | tail -n +3 | awk -F'|' '{ s = $4; gsub(/^ +| +$/, "", s); print s }')
total=$(wc -l <<<"$rows" | tr -d ' ')  # BSD wc pads the count
counts=$("$SED_RS" -e 's/:.*//' <<<"$rows" | LC_ALL=C sort | uniq -c | awk '{ printf "%s%s %d", (NR > 1 ? ", " : ""), $2, $1 }')
ranks=$(grep '^missing: ' <<<"$rows" | "$SED_RS" -e 's/^missing: //' | LC_ALL=C sort | uniq -c |
        LC_ALL=C sort -k1,1nr -k2 | head -10 | awk '{ c = $1; $1 = ""; sub(/^ /, ""); printf "- %s (%d)\n", $0, c }')
report=$(
    echo "$total examples: $counts"
    if [[ -n "$ranks" ]]; then
        echo
        echo "Most common first missing word (top 10):"
        echo
        echo "$ranks"
    fi
    echo
    echo "$table"
)
echo "$report"
if [[ "${1:-}" == "--write" ]]; then
    {
        echo "# Example parity (generated)"
        echo
        echo "Generated by \`scripts/parity-examples.sh --write\`; do not edit."
        echo "Each program in \`examples/\` is run on the portable core with stdin"
        echo "closed and a ${LIMIT}s limit. See [parity.md](parity.md) for what the"
        echo "statuses mean and which areas are planned."
        echo
        echo "$report"
    } > "$root/docs/parity-examples.md"
fi
